import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../support/test_database.dart';

/// The Drift schema is the single source of truth. This test renders it into
/// the three files native code consumes and fails when any of them is stale:
///
/// * `schema/finance_schema.sql` – human-readable reference.
/// * `ios/SharedStorage/FinanceSchema.swift` – embedded by SharedSQLiteManager.
/// * `android/.../capture/FinanceSchema.kt` – embedded by FinanceStore.
///
/// Refresh with `UPDATE_SCHEMA=1 flutter test test/database/schema_snapshot_test.dart`.
void main() {
  late List<String> statements;

  setUpAll(() async {
    final db = openTestDatabase();
    final rows = await db
        .customSelect(
          "SELECT type, name, sql FROM sqlite_master "
          "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' "
          "ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, name",
        )
        .get();
    await db.close();
    statements = [
      for (final row in rows) _ifNotExists(row.read<String>('sql')),
      'INSERT OR IGNORE INTO budget_config (id) VALUES (1)',
    ];
  });

  void expectSnapshot(String path, String generated) {
    final file = File(path);
    if (Platform.environment['UPDATE_SCHEMA'] == '1') {
      file.writeAsStringSync(generated);
    }
    expect(file.existsSync(), isTrue, reason: 'run with UPDATE_SCHEMA=1');
    expect(file.readAsStringSync(), generated, reason: '$path is stale');
  }

  test('schema/finance_schema.sql', () {
    final buffer = StringBuffer()
      ..writeln('-- GENERATED from the Drift schema by')
      ..writeln(
        '-- test/database/schema_snapshot_test.dart. Do not edit by hand.',
      )
      ..writeln(
        '-- Native writers run these with IF NOT EXISTS semantics; Drift',
      )
      ..writeln('-- owns PRAGMA user_version and migrations.')
      ..writeln()
      ..writeln('PRAGMA journal_mode = WAL;')
      ..writeln('PRAGMA busy_timeout = 5000;')
      ..writeln('PRAGMA foreign_keys = ON;');
    for (final sql in statements) {
      buffer
        ..writeln()
        ..writeln('$sql;');
    }
    expectSnapshot('schema/finance_schema.sql', buffer.toString());
  });

  test('ios/SharedStorage/FinanceSchema.swift', () {
    final buffer = StringBuffer()
      ..writeln(
        '// GENERATED by test/database/schema_snapshot_test.dart from the Drift',
      )
      ..writeln('// schema. Do not edit by hand.')
      ..writeln()
      ..writeln(
        '/// DDL for `finance.sqlite`, idempotent (IF NOT EXISTS / OR IGNORE).',
      )
      ..writeln(
        '/// Drift owns `PRAGMA user_version`; never set it from Swift.',
      )
      ..writeln('enum FinanceSchema {')
      ..writeln('  static let statements: [String] = [');
    for (final sql in statements) {
      buffer.writeln('    #"$sql"#,');
    }
    buffer
      ..writeln('  ]')
      ..writeln('}');
    expectSnapshot('ios/SharedStorage/FinanceSchema.swift', buffer.toString());
  });

  test('android FinanceSchema.kt', () {
    final buffer = StringBuffer()
      ..writeln(
        '// GENERATED by test/database/schema_snapshot_test.dart from the Drift',
      )
      ..writeln('// schema. Do not edit by hand.')
      ..writeln('package com.splitburn.app.capture')
      ..writeln()
      ..writeln(
        '/** DDL for `finance.sqlite`, idempotent (IF NOT EXISTS / OR IGNORE). */',
      )
      ..writeln('internal object FinanceSchema {')
      ..writeln('    val statements: List<String> = listOf(');
    for (final sql in statements) {
      expect(sql.contains(r'$'), isFalse, reason: 'breaks Kotlin raw strings');
      buffer.writeln('        """$sql""",');
    }
    buffer
      ..writeln('    )')
      ..writeln('}');
    expectSnapshot(
      'android/app/src/main/kotlin/com/splitburn/app/capture/FinanceSchema.kt',
      buffer.toString(),
    );
  });
}

String _ifNotExists(String sql) => sql.replaceFirstMapped(
  RegExp(r'^CREATE (TABLE|INDEX|VIEW|TRIGGER) (?!IF NOT EXISTS)'),
  (m) => 'CREATE ${m[1]} IF NOT EXISTS ',
);
